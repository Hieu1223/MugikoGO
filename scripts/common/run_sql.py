#!/usr/bin/env python3
"""
General-purpose SQL runner script.
Supports running raw SQL queries, executing SQL files, or dumping the DB.
"""

import os
import sys
import argparse
import psycopg2
import subprocess

# Windows consoles (e.g. cp932) may not be able to encode the emoji output
# used below; reconfigure to UTF-8 with replacement so real errors are shown.
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")


def get_db_path():
    """Get database path from environment or default."""
    return os.getenv("DB_PATH", "postgres://postgres:postgres@localhost:5432/mugiko?sslmode=disable")


def execute_query(conn, query):
    """Execute a raw SQL query string."""
    cursor = conn.cursor()
    try:
        print(f"Executing query: {query}")
        cursor.execute(query)
        conn.commit()
        
        if cursor.description:
            rows = cursor.fetchall()
            print(f"\n✅ Query returned {len(rows)} row(s):")
            for row in rows:
                print(row)
        else:
            print(f"✅ Success! Database response: {cursor.statusmessage}")
            
    except psycopg2.Error as e:
        conn.rollback()
        print(f"\n❌ Query Execution Failed!")
        print(f"Error: {e}")
        sys.exit(1)
    finally:
        cursor.close()


def execute_file(conn, file_path):
    """Read and execute a SQL file."""
    if not os.path.isfile(file_path):
        print(f"❌ Error: File '{file_path}' does not exist.")
        sys.exit(1)

    cursor = conn.cursor()
    try:
        print(f"Reading SQL from: {file_path}")
        with open(file_path, "r", encoding="utf-8") as f:
            sql_script = f.read()

        print("Executing SQL script...")
        cursor.execute(sql_script)
        conn.commit()
        print(f"✅ Success! Database response: {cursor.statusmessage or 'OK'}")
        
    except psycopg2.Error as e:
        conn.rollback()
        print(f"\n❌ File Execution Failed!")
        print(f"Error: {e}")
        sys.exit(1)
    finally:
        cursor.close()

def dump_database(output_path):
    """Create a logical dump of the database using only psycopg2."""
    db_path = get_db_path()
    
    # Ensure output directory exists
    output_dir = os.path.dirname(output_path)
    if output_dir and not os.path.exists(output_dir):
        os.makedirs(output_dir)

    print(f"Starting logical dump to {output_path}...")
    
    try:
        conn = psycopg2.connect(db_path)
        cursor = conn.cursor()
        
        # 1. Get all table names
        cursor.execute("""
            SELECT tablename FROM pg_tables 
            WHERE schemaname = 'public'
            ORDER BY tablename;
        """)
        tables = [row[0] for row in cursor.fetchall()]
        
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write("-- Logical Dump generated by run_sql.py\n")
            f.write("BEGIN;\n\n")
            
            for table in tables:
                print(f"  Dumping table: {table}...")
                
                # 2. Get column names
                cursor.execute(f"""
                    SELECT column_name FROM information_schema.columns 
                    WHERE table_name = '{table}' AND table_schema = 'public'
                    ORDER BY ordinal_position;
                """)
                columns = [row[0] for row in cursor.fetchall()]
                
                if not columns:
                    continue
                    
                col_names = ", ".join(columns)
                
                # 3. Get all rows
                cursor.execute(f"SELECT * FROM \"{table}\"")
                rows = cursor.fetchall()
                
                for row in rows:
                    # Format values: quote strings, handle None
                    formatted_values = []
                    for val in row:
                        if val is None:
                            formatted_values.append("NULL")
                        elif isinstance(val, str):
                            # Escape single quotes for SQL
                            escaped = val.replace("'", "''")
                            formatted_values.append(f"'{escaped}'")
                        else:
                            formatted_values.append(str(val))
                    
                    values_str = ", ".join(formatted_values)
                    f.write(f"INSERT INTO \"{table}\" ({col_names}) VALUES ({values_str});\n")
            
            f.write("\nCOMMIT;\n")
            
        cursor.close()
        conn.close()
        print(f"✅ Logical dump saved to {output_path}")
        
    except Exception as e:
        print(f"❌ Dump failed: {e}")
        sys.exit(1)

def main():
    parser = argparse.ArgumentParser(
        description="Run SQL queries, files, or dump the database."
    )
    
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("-q", "--query", help="Raw SQL query string to execute")
    group.add_argument("-f", "--file", help="Path to the SQL file to execute")
    group.add_argument("--dump", help="Path to save database snapshot (e.g., backup/snapshot.sql)")
    
    args = parser.parse_args()
    db_path = get_db_path()
    print(f"Target Database: {db_path.split('@')[-1] if '@' in db_path else db_path}")

    # If dumping, we don't need a psycopg2 connection, we use subprocess
    if args.dump:
        dump_database(args.dump)
        return

    try:
        conn = psycopg2.connect(db_path)
        try:
            if args.query:
                execute_query(conn, args.query)
            elif args.file:
                execute_file(conn, args.file)
        finally:
            conn.close()
            print("Database connection closed.")
    except psycopg2.OperationalError as e:
        print(f"\n❌ Failed to connect to database:")
        print(f"Error: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()